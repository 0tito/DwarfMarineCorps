using System.Numerics;
using Content.Shared._DwarfMC.Medical.DwarfMed;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Utility;

namespace Content.Client._RMC14.Medical.Scanner;

[GenerateTypedNameReferences]
public sealed partial class HealthScannerBodyControl : UIWidget
{
    private const int PixelScale = 6;

    private static readonly Dictionary<BodyZone, PartBounds> PartRegions = new()
    {
        [BodyZone.Head] = new(12, 3, 7, 7),
        [BodyZone.Chest] = new(11, 10, 9, 7),
        [BodyZone.Groin] = new(11, 17, 9, 5),
        [BodyZone.RightArm] = new(7, 10, 5, 6),
        [BodyZone.LeftArm] = new(19, 10, 5, 6),
        [BodyZone.RightHand] = new(7, 16, 4, 4),
        [BodyZone.LeftHand] = new(20, 16, 4, 4),
        [BodyZone.RightLeg] = new(11, 20, 4, 6),
        [BodyZone.LeftLeg] = new(16, 20, 4, 6),
        [BodyZone.RightFoot] = new(9, 26, 6, 3),
        [BodyZone.LeftFoot] = new(16, 26, 6, 3),
    };

    private const int MarkerSize = 28;
    private const int MarkerGap = -10;

    private readonly SpriteSystem _sprite;
    private readonly Dictionary<BodyZone, TextureRect> _partTextures = new();
    private readonly Dictionary<BodyZone, TextureRect> _fractureMarkers = new();
    private readonly Dictionary<BodyZone, TextureRect> _bleedingMarkers = new();
    private readonly Dictionary<(BodyZone Zone, DwarfPartSeverity Severity), Texture> _textureCache = new();
    private readonly PanelContainer _hoverHighlight;
    private readonly PanelContainer _selectedHighlight;
    private readonly Texture _fractureTexture;
    private readonly Texture _bleedingTexture;

    public BodyZone SelectedZone { get; private set; } = BodyZone.Chest;

    public event Action<BodyZone>? PartSelected;

    public HealthScannerBodyControl()
    {
        RobustXamlLoader.Load(this);
        _sprite = IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<SpriteSystem>();
        _fractureTexture = _sprite.Frame0(new SpriteSpecifier.Rsi(
            new ResPath("/Textures/_DwarfMC/Interface/Medical/Damages.rsi"),
            "fracture"));
        _bleedingTexture = _sprite.Frame0(new SpriteSpecifier.Rsi(
            new ResPath("/Textures/_DwarfMC/Interface/Medical/Damages.rsi"),
            "bleeding"));

        _selectedHighlight = CreateHighlight(
            new Color(0.3f, 0.75f, 1f, 0.12f),
            new Color(0.3f, 0.75f, 1f, 0.9f));
        _hoverHighlight = CreateHighlight(
            new Color(1f, 1f, 1f, 0.10f),
            new Color(1f, 1f, 1f, 0.8f));

        foreach (var zone in PartRegions.Keys)
        {
            var texture = new TextureRect
            {
                SetSize = new Vector2(192, 192),
                Stretch = TextureRect.StretchMode.Scale,
                MouseFilter = MouseFilterMode.Ignore,
                Texture = GetTexture(zone, DwarfPartSeverity.Healthy),
            };
            _partTextures[zone] = texture;
            PartContainer.AddChild(texture);
        }

        PartContainer.AddChild(_selectedHighlight);
        PartContainer.AddChild(_hoverHighlight);

        foreach (var zone in PartRegions.Keys)
        {
            var fractureMarker = CreateMarker(_fractureTexture, "Fractured");
            var bleedingMarker = CreateMarker(_bleedingTexture, "Bleeding");
            _fractureMarkers[zone] = fractureMarker;
            _bleedingMarkers[zone] = bleedingMarker;
            PartContainer.AddChild(fractureMarker);
            PartContainer.AddChild(bleedingMarker);
        }

        foreach (var (zone, bounds) in PartRegions)
        {
            var button = new TextureButton
            {
                TextureNormal = Texture.Transparent,
                SetSize = new Vector2(bounds.Width * PixelScale, bounds.Height * PixelScale),
                Margin = new Thickness(bounds.X * PixelScale, bounds.Y * PixelScale, 0, 0),
                HorizontalAlignment = HAlignment.Left,
                VerticalAlignment = VAlignment.Top,
            };
            button.OnPressed += _ => Select(zone);
            button.OnMouseEntered += _ => ShowHover(zone);
            button.OnMouseExited += _ => _hoverHighlight.Visible = false;
            PartContainer.AddChild(button);
        }

        UpdateSelectedHighlight();
    }

    public void SetScan(IReadOnlyList<DwarfBodyPartScan> parts, IReadOnlyList<DwarfOrganScan> organs)
    {
        foreach (var marker in _fractureMarkers.Values)
        {
            marker.Visible = false;
        }

        foreach (var marker in _bleedingMarkers.Values)
        {
            marker.Visible = false;
        }

        foreach (var scan in parts)
        {
            if (!Enum.TryParse<BodyZone>(scan.SlotId, out var zone) ||
                !_partTextures.TryGetValue(zone, out var texture))
            {
                continue;
            }

            var severity = DwarfPartStatus.GetSeverity(scan, organs);
            texture.Texture = GetTexture(zone, severity);
            UpdateDamageMarkers(zone, scan.Fractured, scan.InternalBleeding || scan.StumpBleeding);
        }
    }

    public void SetSelected(BodyZone zone)
    {
        SelectedZone = zone;
        UpdateSelectedHighlight();
    }

    private void Select(BodyZone zone)
    {
        SelectedZone = zone;
        UpdateSelectedHighlight();
        PartSelected?.Invoke(zone);
    }

    private void UpdateDamageMarkers(BodyZone zone, bool fractured, bool bleeding)
    {
        if (!PartRegions.TryGetValue(zone, out var bounds))
            return;

        var centerX = (bounds.X + bounds.Width / 2f) * PixelScale;
        var centerY = (bounds.Y + bounds.Height / 2f) * PixelScale;
        var markerY = centerY - MarkerSize / 2f;

        if (fractured && bleeding)
        {
            var left = centerX - (MarkerSize + MarkerGap / 2f);
            PositionMarker(_fractureMarkers[zone], left, markerY);
            PositionMarker(_bleedingMarkers[zone], left + MarkerSize + MarkerGap, markerY);
        }
        else if (fractured)
        {
            PositionMarker(_fractureMarkers[zone], centerX - MarkerSize / 2f, markerY);
        }
        else if (bleeding)
        {
            PositionMarker(_bleedingMarkers[zone], centerX - MarkerSize / 2f, markerY);
        }

        _fractureMarkers[zone].Visible = fractured;
        _bleedingMarkers[zone].Visible = bleeding;
    }

    private static void PositionMarker(TextureRect marker, float x, float y)
    {
        marker.Margin = new Thickness(x, y, 0, 0);
    }

    private static TextureRect CreateMarker(Texture texture, string toolTip)
    {
        return new TextureRect
        {
            Texture = texture,
            SetSize = new Vector2(MarkerSize, MarkerSize),
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            MouseFilter = MouseFilterMode.Ignore,
            ToolTip = toolTip,
            Visible = false,
            HorizontalAlignment = HAlignment.Left,
            VerticalAlignment = VAlignment.Top,
        };
    }

    private Texture GetTexture(BodyZone zone, DwarfPartSeverity severity)
    {
        var key = (zone, severity);
        if (_textureCache.TryGetValue(key, out var cached))
            return cached;

        var rsiName = DwarfPartStatus.GetRsiName(zone);
        var specifier = new SpriteSpecifier.Rsi(
            new ResPath($"/Textures/_DwarfMC/Interface/Medical/PartStatus/{rsiName}.rsi"),
            $"{rsiName}_{(int) severity}");
        var texture = _sprite.Frame0(specifier);
        _textureCache[key] = texture;
        return texture;
    }

    private void ShowHover(BodyZone zone)
    {
        PositionHighlight(_hoverHighlight, zone);
        _hoverHighlight.Visible = true;
    }

    private void UpdateSelectedHighlight()
    {
        PositionHighlight(_selectedHighlight, SelectedZone);
        _selectedHighlight.Visible = true;
    }

    private static void PositionHighlight(PanelContainer panel, BodyZone zone)
    {
        if (!PartRegions.TryGetValue(zone, out var bounds))
            return;

        panel.SetSize = new Vector2(bounds.Width * PixelScale, bounds.Height * PixelScale);
        panel.Margin = new Thickness(bounds.X * PixelScale, bounds.Y * PixelScale, 0, 0);
        panel.HorizontalAlignment = HAlignment.Left;
        panel.VerticalAlignment = VAlignment.Top;
    }

    private static PanelContainer CreateHighlight(Color background, Color border)
    {
        return new PanelContainer
        {
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = background,
                BorderColor = border,
                BorderThickness = new Thickness(1),
            },
            MouseFilter = MouseFilterMode.Ignore,
            Visible = false,
        };
    }

    private readonly record struct PartBounds(int X, int Y, int Width, int Height);
}
