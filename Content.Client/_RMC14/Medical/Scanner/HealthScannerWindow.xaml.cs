using Content.Shared._DwarfMC.Medical.DwarfMed;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.Medical.Scanner;

[GenerateTypedNameReferences]
public sealed partial class HealthScannerWindow : DefaultWindow
{
    public BodyZone SelectedDwarfPart { get; set; } = BodyZone.Chest;

    public Action<BodyZone>? OnDwarfPartSelected { get; set; }

    public HealthScannerWindow()
    {
        RobustXamlLoader.Load(this);

        BodyControl.PartSelected += zone =>
        {
            SelectedDwarfPart = zone;
            OnDwarfPartSelected?.Invoke(zone);
        };
    }
}
