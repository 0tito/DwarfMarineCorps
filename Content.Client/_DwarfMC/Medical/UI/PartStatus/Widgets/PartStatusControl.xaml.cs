using Content.Shared._DwarfMC.Medical.DwarfMed;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;
using Robust.Shared.Utility;

namespace Content.Client._DwarfMC.Medical.UI.PartStatus.Widgets;

[GenerateTypedNameReferences]
public sealed partial class PartStatusControl : UIWidget
{
    private readonly PartStatusUIController _controller;
    private readonly Dictionary<BodyZone, TextureRect> _partStatusControls;
    private readonly Dictionary<BodyZone, Texture?[]> _textures = new();

    public PartStatusControl()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        _controller = UserInterfaceManager.GetUIController<PartStatusUIController>();
        _partStatusControls = new Dictionary<BodyZone, TextureRect>
        {
            [BodyZone.Head] = DollHead,
            [BodyZone.Chest] = DollTorso,
            [BodyZone.Groin] = DollGroin,
            [BodyZone.LeftArm] = DollLeftArm,
            [BodyZone.LeftHand] = DollLeftHand,
            [BodyZone.RightArm] = DollRightArm,
            [BodyZone.RightHand] = DollRightHand,
            [BodyZone.LeftLeg] = DollLeftLeg,
            [BodyZone.LeftFoot] = DollLeftFoot,
            [BodyZone.RightLeg] = DollRightLeg,
            [BodyZone.RightFoot] = DollRightFoot,
        };

        MouseFilter = MouseFilterMode.Stop;
        OnKeyBindDown += OnClicked;
    }

    public void SetTextures(IReadOnlyDictionary<BodyZone, DwarfPartSeverity> state)
    {
        foreach (var (zone, severity) in state)
        {
            if (!_partStatusControls.TryGetValue(zone, out var control))
                continue;

            if (GetTexture(zone, severity) is { } texture)
                control.Texture = texture;
        }
    }

    private Texture? GetTexture(BodyZone zone, DwarfPartSeverity severity)
    {
        var index = (int) severity;
        var max = (int) DwarfPartSeverity.Disabled;
        if (index < 0 || index > max)
            return null;

        if (!_textures.TryGetValue(zone, out var textures))
        {
            textures = new Texture?[max + 1];
            _textures[zone] = textures;
        }

        if (textures[index] is { } cached)
            return cached;

        var rsiName = DwarfPartStatus.GetRsiName(zone);
        var specifier = new SpriteSpecifier.Rsi(
            new ResPath($"/Textures/_DwarfMC/Interface/Medical/PartStatus/{rsiName}.rsi"),
            $"{rsiName}_{index}");
        textures[index] = _controller.GetTexture(specifier);
        return textures[index];
    }

    public void SetVisible(bool visible)
    {
        Visible = visible;
    }

    private void OnClicked(GUIBoundKeyEventArgs args)
    {
        if (args.Function != EngineKeyFunctions.UIClick)
            return;

        _controller.RequestPartStatus();
        args.Handle();
    }
}
