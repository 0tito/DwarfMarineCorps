using Content.Shared._DwarfMC.Medical.DwarfMed;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._DwarfMC.Medical.UI;

[GenerateTypedNameReferences]
public sealed partial class DwarfMedicalBodyOverlay : UIWidget
{
    private readonly Dictionary<BodyZone, PartControls> _parts;

    public BodyZone? SelectedPart { get; private set; }

    public event Action<BodyZone>? PartSelected;

    public DwarfMedicalBodyOverlay()
    {
        RobustXamlLoader.Load(this);

        _parts = new Dictionary<BodyZone, PartControls>
        {
            [BodyZone.Chest] = new(ChestButton, ChestSelected, ChestHover),
            [BodyZone.Groin] = new(GroinButton, GroinSelected, GroinHover),
            [BodyZone.RightArm] = new(RightArmButton, RightArmSelected, RightArmHover),
            [BodyZone.LeftArm] = new(LeftArmButton, LeftArmSelected, LeftArmHover),
            [BodyZone.RightLeg] = new(RightLegButton, RightLegSelected, RightLegHover),
            [BodyZone.LeftLeg] = new(LeftLegButton, LeftLegSelected, LeftLegHover),
            [BodyZone.RightHand] = new(RightHandButton, RightHandSelected, RightHandHover),
            [BodyZone.LeftHand] = new(LeftHandButton, LeftHandSelected, LeftHandHover),
            [BodyZone.RightFoot] = new(RightFootButton, RightFootSelected, RightFootHover),
            [BodyZone.LeftFoot] = new(LeftFootButton, LeftFootSelected, LeftFootHover),
            [BodyZone.Head] = new(HeadButton, HeadSelected, HeadHover),
        };

        foreach (var (part, controls) in _parts)
        {
            controls.Button.TextureNormal = Texture.Transparent;
            controls.Button.OnPressed += _ => SelectPart(part);
            controls.Button.OnMouseEntered += _ => controls.Hover.Visible = true;
            controls.Button.OnMouseExited += _ => controls.Hover.Visible = false;
        }

        SetSelected(BodyZone.Chest);
    }

    public void SelectPart(BodyZone part)
    {
        SetSelected(part);
        PartSelected?.Invoke(part);
    }

    public void SetSelected(BodyZone part)
    {
        SelectedPart = part;

        foreach (var (otherPart, controls) in _parts)
        {
            controls.Selected.Visible = otherPart == part;
        }
    }

    private sealed record PartControls(TextureButton Button, TextureRect Selected, TextureRect Hover);
}
